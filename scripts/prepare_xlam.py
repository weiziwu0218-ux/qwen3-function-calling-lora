#!/usr/bin/env python3
"""Convert Salesforce xLAM function-calling 60k into Qwen3-1.7B training data.

The official dataset stores each row as query / tools / answers. Qwen3-1.7B's
chat template (tokenizer_config.json on Qwen/Qwen3-1.7B) expects OpenAI-style
JSON-schema tools and Hermes-style <tool_call> assistant turns. This script
renders every row with that template and writes one shared validation split
plus nested training subsets.

Splits (seed 42), matching the proposal:

- Hold out 1,000 validation rows. Every later run, including the LoRA-rank
  experiments, should use this same file.
- From the remaining 59,000 rows, write nested training sets of 1,000, 5,000,
  10,000, 30,000, and the full 59,000. Each smaller file is an exact prefix of
  the next, so a gain from 5k to 10k is the effect of extra data rather than a
  different sample.
- Rows are stratified by generator (the dataset card: ids 0-33658 are DeepSeek,
  the rest are Mixtral) and by single vs multiple function calls, which lines
  up with the BFCL simple vs parallel split. Prefixes keep that mix.

Loss during SFT should be on ``completion`` only. ``prompt + completion``
equals ``text``.
"""

